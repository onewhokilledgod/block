const CSS_STYLE_RULE_TYPE = 1;
const PROBE_RULE = ":root { --block-cosmetic-selector-probe: 0; }";

export const DEFAULT_MAX_COSMETIC_SELECTORS = 10_000;
export const DEFAULT_MAX_COSMETIC_SELECTOR_LENGTH = 4_096;

export type CosmeticSelectorDiagnosticCode =
	| "emptySelector"
	| "invalidSelector"
	| "selectorTooLong"
	| "selectorLimitExceeded"
	| "cssParserUnavailable";

export interface CosmeticSelectorDiagnostic {
	code: CosmeticSelectorDiagnosticCode;
	selector?: string;
	message: string;
}

export interface CosmeticSelectorProcessingResult {
	/** Browser-normalized selectors that passed CSSOM validation. */
	selectors: string[];
	/** CSS containing only validated selectors and a fixed hiding declaration. */
	cssText: string;
	diagnostics: CosmeticSelectorDiagnostic[];
}

export interface CosmeticSelectorProcessorOptions {
	/** Maximum number of distinct selectors to validate in one call. */
	maxSelectors?: number;
	/** Maximum accepted selector length, measured in UTF-16 code units. */
	maxSelectorLength?: number;
	/** Injectable for tests; production uses the browser's native CSS parser. */
	createStyleSheet?: () => CSSStyleSheet;
}

interface SelectorValidationResult {
	selector: string | null;
	parserFailed: boolean;
}

function readLimit(
	value: number | undefined,
	fallback: number,
	minimum: number
): number {
	if (value === undefined) {
		return fallback;
	}

	if (!Number.isSafeInteger(value) || value < minimum) {
		throw new RangeError(`Expected an integer greater than or equal to ${minimum}`);
	}

	return value;
}

function diagnostic(
	code: CosmeticSelectorDiagnosticCode,
	message: string,
	selector?: string
): CosmeticSelectorDiagnostic {
	return selector === undefined
		? { code, message }
		: { code, message, selector };
}

/**
 * Validates ABP cosmetic selectors and creates safe CSS rules.
 *
 * Validation is delegated to the browser CSS parser instead of attempting to
 * approximate the CSS grammar with regular expressions. A probe style rule is
 * kept at index 0 so an input at-rule (notably @import) cannot be inserted at
 * the beginning of the detached stylesheet. Each candidate is inserted after
 * the probe, accepted only when it becomes exactly one CSSStyleRule, and then
 * removed again.
 *
 * The input controls only the selector. The declaration block is always
 * generated by this module and cannot be supplied by a filter list.
 */
export class CosmeticSelectorProcessor {
	private readonly maxSelectors: number;
	private readonly maxSelectorLength: number;
	private readonly createStyleSheet: () => CSSStyleSheet;

	constructor(options: CosmeticSelectorProcessorOptions = {}) {
		this.maxSelectors = readLimit(
			options.maxSelectors,
			DEFAULT_MAX_COSMETIC_SELECTORS,
			0
		);
		this.maxSelectorLength = readLimit(
			options.maxSelectorLength,
			DEFAULT_MAX_COSMETIC_SELECTOR_LENGTH,
			1
		);
		this.createStyleSheet =
			options.createStyleSheet ?? (() => new CSSStyleSheet());
	}

	process(selectors: readonly string[]): CosmeticSelectorProcessingResult {
		const acceptedSelectors: string[] = [];
		const diagnostics: CosmeticSelectorDiagnostic[] = [];
		const seenInputSelectors = new Set<string>();
		const seenValidatedSelectors = new Set<string>();

		if (selectors.length === 0) {
			return { selectors: acceptedSelectors, cssText: "", diagnostics };
		}

		let stylesheet: CSSStyleSheet;

		try {
			stylesheet = this.createStyleSheet();
			stylesheet.insertRule(PROBE_RULE, 0);

			if (
				stylesheet.cssRules.length !== 1 ||
				stylesheet.cssRules[0]?.type !== CSS_STYLE_RULE_TYPE
			) {
				throw new Error("The CSS parser did not create the probe style rule");
			}
		} catch {
			return {
				selectors: acceptedSelectors,
				cssText: "",
				diagnostics: [
					diagnostic(
						"cssParserUnavailable",
					"The browser CSS parser is unavailable; cosmetic rules were skipped."
					)
				]
			};
		}

		let checkedSelectors = 0;

		for (const rawSelector of selectors) {
			const selector = rawSelector.trim();

			if (selector.length === 0) {
				diagnostics.push(
					diagnostic("emptySelector", "Cosmetic selector is empty.", rawSelector)
				);
				continue;
			}

			if (seenInputSelectors.has(selector)) {
				continue;
			}

			seenInputSelectors.add(selector);

			if (checkedSelectors >= this.maxSelectors) {
				diagnostics.push(
					diagnostic(
						"selectorLimitExceeded",
						`The selector limit (${this.maxSelectors}) was reached; remaining selectors were skipped.`,
						selector
					)
				);
				break;
			}

			checkedSelectors += 1;

			if (selector.length > this.maxSelectorLength) {
				diagnostics.push(
					diagnostic(
						"selectorTooLong",
						`Selector exceeds the maximum length of ${this.maxSelectorLength} characters.`,
						selector
					)
				);
				continue;
			}

			const validation = this.validateSelector(stylesheet, selector);

			if (validation.parserFailed) {
				diagnostics.push(
					diagnostic(
						"cssParserUnavailable",
						"The browser CSS parser failed while validating selectors; remaining selectors were skipped."
					)
				);
				break;
			}

			if (!validation.selector) {
				diagnostics.push(
					diagnostic(
						"invalidSelector",
						"Selector is not a valid CSS style-rule selector in this browser.",
						selector
					)
				);
				continue;
			}

			if (seenValidatedSelectors.has(validation.selector)) {
				continue;
			}

			seenValidatedSelectors.add(validation.selector);
			acceptedSelectors.push(validation.selector);
		}

		const cssText = acceptedSelectors
			.map(selector => `${selector} { display: none !important; }`)
			.join("\n");

		return { selectors: acceptedSelectors, cssText, diagnostics };
	}

	private validateSelector(
		stylesheet: CSSStyleSheet,
		selector: string
	): SelectorValidationResult {
		let normalizedSelector: string | null = null;
		let parserFailed = false;

		try {
			// Insert after the probe. This also prevents top-level @import rules
			// from being accepted at the stylesheet's required first position.
			stylesheet.insertRule(
				`${selector} { display: none !important; }`,
				1
			);

			const rule = stylesheet.cssRules[1];

			if (
				stylesheet.cssRules.length === 2 &&
				rule?.type === CSS_STYLE_RULE_TYPE
			) {
				const selectorText = (rule as CSSStyleRule).selectorText.trim();
				normalizedSelector = selectorText.length > 0 ? selectorText : null;
			}
		} catch {
			// SyntaxError is expected for malformed or unsupported selectors.
		} finally {
			try {
				// Keep only the probe; remove any candidate rule, including an
				// at-rule that the CSS parser accepted instead of a style rule.
				while (stylesheet.cssRules.length > 1) {
					stylesheet.deleteRule(stylesheet.cssRules.length - 1);
				}

				if (
					stylesheet.cssRules.length !== 1 ||
					stylesheet.cssRules[0]?.type !== CSS_STYLE_RULE_TYPE
				) {
					parserFailed = true;
				}
			} catch {
				parserFailed = true;
			}
		}

		return { selector: normalizedSelector, parserFailed };
	}
}
